const DICTS: Record<Lang, Dict> = { uz: UZ, ru: RU, en: EN };

interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  localizedName: (p: { nameUz: string; nameRu: string; nameEn: string }) => string;
  localizedDesc: (p: { descriptionUz: string; descriptionRu: string; descriptionEn: string }) => string;
  categoryName: (c: Category) => string;
}

const I18nCtx = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const v = localStorage.getItem(LANG_KEY);
      if (v === "uz" || v === "ru" || v === "en") return v;
    } catch {
      /* noop */
    }
    return "uz";
  });

  useEffect(() => {
    try {
      localStorage.setItem(LANG_KEY, lang);
    } catch {
      /* noop */
    }
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => setLangState(l), []);
  const t = useCallback((key: string) => DICTS[lang][key] ?? DICTS.uz[key] ?? key, [lang]);

  const pick = useCallback(
    (uz: string, ru: string, en: string) => (lang === "ru" ? ru : lang === "en" ? en : uz),
    [lang]
  );

  const value: I18nValue = useMemo(
    () => ({
      lang,
      setLang,
      t,
      localizedName: (p) => pick(p.nameUz, p.nameRu, p.nameEn),
      localizedDesc: (p) => pick(p.descriptionUz, p.descriptionRu, p.descriptionEn),
      categoryName: (c) => pick(c.nameUz, c.nameRu, c.nameEn),
    }),
    [lang, setLang, t, pick]
  );

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

export function useT() {
  return useI18n().t;
}

export function productName(p: Product, lang: Lang): string {
  return lang === "ru" ? p.nameRu : lang === "en" ? p.nameEn : p.nameUz;
}

